//! Desktop fallback country names and regional flag sequences.
use super::format::CountryInfo;
pub fn country_name_by_iso2<'a>(iso: &str, countries: &'a [CountryInfo]) -> &'a str {
    if !countries.is_empty() {
        return countries
            .iter()
            .find(|c| c.iso2 == iso)
            .map_or("", |c| c.name.as_str());
    }
    COUNTRIES
        .binary_search_by_key(&iso, |row| row.0)
        .map_or("", |index| COUNTRIES[index].1)
}
pub fn flag_emoji_by_iso2(iso: &str) -> String {
    if iso.len() != 2 || !iso.bytes().all(|b| b.is_ascii_uppercase()) {
        return String::new();
    }
    if iso == "FT" {
        return "🏴‍☠️".into();
    }
    iso.bytes()
        .filter_map(|b| char::from_u32(0x1f1e6 + u32::from(b - b'A')))
        .collect()
}

